const designsEndMarker = 'export const BUSINESS_PACKAGES: BusinessPackage[] = [';

const startIdx = mockDataContent.indexOf(designsStartMarker);
const endIdx = mockDataContent.indexOf(designsEndMarker);

if (startIdx === -1 || endIdx === -1) {
  console.error('Could not find markers in mockData.ts');
  process.exit(1);
}

// Filter existing designs so none are duplicates
const existingFiltered = ORIGINAL_25_DESIGNS.filter(d => !featuredIds.has(d.id));

// Collect all other new designs
const otherLogos = LOGO_PROJECTS.filter(p => !featuredIds.has(p.id));
const otherMenus = MENU_PROJECTS.filter(p => !featuredIds.has(p.id));
const otherPosters = POSTER_PROJECTS.filter(p => !featuredIds.has(p.id));
const otherSocial = SOCIAL_PROJECTS.filter(p => !featuredIds.has(p.id));
const otherPackaging = PACKAGING_PROJECTS.filter(p => !featuredIds.has(p.id));

// Assemble combined array
const ALL_DESIGNS = [
  ...FEATURED_TOP,
  ...otherLogos,
  ...otherMenus,
  ...otherPosters,
  ...otherSocial,
  ...otherPackaging,
  ...existingFiltered
];

console.log('Total designs assembled:', ALL_DESIGNS.length);

// Format as clean TypeScript code using JSON.stringify
const designsCodeFormatted = 'export const DESIGNS_PROJECTS: DesignProject[] = ' +
  JSON.stringify(ALL_DESIGNS, null, 2) + ';\n\n';

let updatedContent = mockDataContent.slice(0, startIdx) + designsCodeFormatted + mockDataContent.slice(endIdx);

// Save updated mockData.ts
fs.writeFileSync(mockDataPath, updatedContent, 'utf8');
console.log('Successfully updated mockData.ts with all 111 designs and product images!');
